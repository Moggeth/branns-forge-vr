// Writes the Timberline range ladder's rung heights for the Blender kit build (see client/timberline-ladder.js).
// Run from multiplayer/: node scripts/timberline-ladder.mjs
import {writeFileSync} from 'node:fs';
import {TIMBERLINE_LADDER,ladderMarks} from '../client/timberline-ladder.js';
const out=new URL('../assets-source/timberline-twinbolt-20261003/source/ladder_marks.json',import.meta.url);
writeFileSync(out,JSON.stringify({note:'Generated by scripts/timberline-ladder.mjs from the shared v3 flight. Elevation frame (Blender): y forward, z up.',eye:TIMBERLINE_LADDER.eye,ladderY:TIMBERLINE_LADDER.ladderY,targetHeight:TIMBERLINE_LADDER.targetHeight,marks:ladderMarks()},null,1)+'\n');
console.log(ladderMarks());
